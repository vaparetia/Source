/**
 * 	For each blend shape, DMAs blend shape infos and deltas to local store
 * 	and blends vertices.  
 *  @param ctx EdgeGeom job context
 * 	@param numShapes the number of shapes
 * 	@param shapeInfosEa the effective address of the first shape info structure.
 */
void edgeGeomProcessBlendShapes(EdgeGeomSpuContext *ctx, uint32_t numShapes, uint32_t shapeInfosEa)
{
	// Blend shapes are not supported in the static geometry path!
	if (ctx->spuConfigInfo.flagsAndUniformTableCount & EDGE_GEOM_FLAG_STATIC_GEOMETRY_FAST_PATH) {
		return;
	}

	uint32_t freePtr = (uint32_t)ctx->freePtr;

	bool interruptsEnabled = spu_readch(SPU_RdMachStat) & 1;
	
	// TODO: Double buffering the input here would improve performance.
	for(uint32_t i = 0; i < numShapes; ++i)
	{
		spu_idisable();

		// dma in the shape Infos to freePtr
		EDGE_DMA_GET(freePtr, shapeInfosEa, sizeof(EdgeGeomBlendShapeInfo), ctx->inputDmaTag, 0, 0);

		// dma in the info->dmaTag w/ barrier
		EDGE_DMA_LIST_GETB(freePtr+sizeof(EdgeGeomBlendShapeInfo), 0,
			(const EdgeDmaListElement*)freePtr, 8, ctx->inputDmaTag, 0, 0);

		// wait for dmas
		EDGE_DMA_WAIT_TAG_STATUS_ALL(1 << ctx->inputDmaTag);

		if(interruptsEnabled)
			spu_ienable();

		EdgeGeomBlendShapeInfo *info = (EdgeGeomBlendShapeInfo *)freePtr;

		// The PPU should not be passing a DMA tag of 0.  If it did, we definitely don't want
		// to process this shape any further, as we'll be working with old/undefined data.
		if (info->dmaTag != 0)
		{
			// The first 2 quads of the actual data is a header, full of four-byte table sizes
			uint32_t *shapeTableSizes = (uint32_t*) ( freePtr + sizeof(EdgeGeomBlendShapeInfo) );
			EdgeGeomVertexStreamDescription *blendStreamDesc =
				(EdgeGeomVertexStreamDescription*)( (uint32_t)shapeTableSizes + 32);
			// All blend shapes use stream description decompression; the format ID field is ignored.
			//if (ctx->spuConfigInfo.vertexDeltaFormatId == 0xFF)
			{
				// EDGE_ASSERT(tableSizes[0] > 0);
				ctx->customFormatInfo.blendStreamDesc = blendStreamDesc;
			}
			void *fixedOffsets = (void*)( (uint32_t)blendStreamDesc + shapeTableSizes[0] );
			void *vertexDeltas = (void*)( (uint32_t)fixedOffsets + shapeTableSizes[1] );
			uint16_t *blendedVertexTable = (uint16_t*)( (uint32_t)vertexDeltas + shapeTableSizes[2] );

			// Each blend shape buffer contains only the non-zero
			// deltas, and an optional (compressed) table of vertex
			// indexes corresponding to those deltas.  The latter
			// table must be decompressed before we use it.
			uint32_t runTableSize = shapeTableSizes[3];
			uint32_t numDeltas = shapeTableSizes[4];
			if (runTableSize > 0)
				DecompressBlendShapeRunTable(blendedVertexTable, runTableSize, numDeltas);
			else
				blendedVertexTable = 0;

			// Only blend if it will actually have an effect.  The PPU should already be checking
			// for zero alphas and not including those shapes in the DMA list, but it never hurts to
			// be cautious!
			if (numDeltas > 0 && info->alpha != 0)
			{
				DecompressVertexesByDescription(ctx, vertexDeltas, fixedOffsets,
					ctx->customFormatInfo.blendStreamDesc, numDeltas, info->alpha, blendedVertexTable);
			}
		}

		shapeInfosEa += sizeof(EdgeGeomBlendShapeInfo);
	}
}
