					qword q1b = si_lqx(pAttrSrc2, srcOffset);
					qword q2a = si_lqx(pAttrSrc3, srcOffset);
					qword q2b = si_lqx(pAttrSrc4, srcOffset);
					qword q3a = si_lqx(pAttrSrc5, srcOffset);
