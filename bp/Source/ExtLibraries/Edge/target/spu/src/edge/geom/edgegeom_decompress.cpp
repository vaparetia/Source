					qword in2 = si_shufb(q2a, q2b, extractAndBroadcastMask);
					qword in3 = si_shufb(q3a, q3b, extractAndBroadcastMask);
					qword in4 = si_shufb(q4a, q4b, extractAndBroadcastMask);
					qword word1_1 = si_rotqmbi(si_rotqmbybi(in1, rshift1), rshift1);
					qword word2_1 = si_rotqmbi(si_rotqmbybi(in2, rshift1), rshift1);
					qword word3_1 = si_rotqmbi(si_rotqmbybi(in3, rshift1), rshift1);
					qword word4_1 = si_rotqmbi(si_rotqmbybi(in4, rshift1), rshift1);
					qword word1_2 = si_rotqmbi(si_rotqmbybi(word1_1, rshift2), rshift2);
