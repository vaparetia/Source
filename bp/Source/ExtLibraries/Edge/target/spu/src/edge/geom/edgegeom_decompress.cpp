						q3b = si_lqx(pAttrSrc6, srcOffset);
						q4a = si_lqx(pAttrSrc7, srcOffset);
						q4b = si_lqx(pAttrSrc8, srcOffset);
						// extract and broadcast
						in1 = si_shufb(q1a, q1b, extractAndBroadcastMask);
						in2 = si_shufb(q2a, q2b, extractAndBroadcastMask);
						in3 = si_shufb(q3a, q3b, extractAndBroadcastMask);
						in4 = si_shufb(q4a, q4b, extractAndBroadcastMask);
						// convert	
						// Right-shift each word to be right-aligned in its
						// own quadword, and then combine the
						// four words from each quad back into one
						// quad again.
						word1_1 = si_rotqmbi(si_rotqmbybi(in1, rshift1), rshift1);
						word2_1 = si_rotqmbi(si_rotqmbybi(in2, rshift1), rshift1);
						word3_1 = si_rotqmbi(si_rotqmbybi(in3, rshift1), rshift1);
						word4_1 = si_rotqmbi(si_rotqmbybi(in4, rshift1), rshift1);
						word1_2 = si_rotqmbi(si_rotqmbybi(word1_1, rshift2), rshift2);
						word2_2 = si_rotqmbi(si_rotqmbybi(word2_1, rshift2), rshift2);
						word3_2 = si_rotqmbi(si_rotqmbybi(word3_1, rshift2), rshift2);
						word4_2 = si_rotqmbi(si_rotqmbybi(word4_1, rshift2), rshift2);
						word1_3 = si_rotqmbi(si_rotqmbybi(word1_2, rshift3), rshift3);
						word2_3 = si_rotqmbi(si_rotqmbybi(word2_2, rshift3), rshift3);
						word3_3 = si_rotqmbi(si_rotqmbybi(word3_2, rshift3), rshift3);
						word4_3 = si_rotqmbi(si_rotqmbybi(word4_2, rshift3), rshift3);
						word1_4 = si_rotm(word1_3, rshifts);
