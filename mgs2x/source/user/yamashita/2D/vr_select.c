/******************************************************************************
 * クリア率の取得
 */
int VRSEL_GetClearPercentage(	/* クリア率 */
	VRSEL_WORK *work,	/* ワーク */
	int        player)	/* プレイヤー */
{
	int weapon, level;
	int cleared, not_cleared;

	cleared     = 0;
	not_cleared = 0;

	/* sneaking mode */
	for(weapon = 0; weapon < SNEAKING_WEAPON_NUM; weapon++)
	{
	for(level = 0; level < SNEAKING_STAGE_NUM; level++)
	{
		if(_sneaking_stage[weapon][level][player] != -1)
		{
		if(_sneaking_stage[weapon][level][player] != -2)
		{
			if(    (_sneaking_stage[weapon][level][player] == 0)
				|| (_sneaking_stage[weapon][level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	}
	/* weapon mode */
	for(weapon = 0; weapon < WEAPON_WEAPON_NUM; weapon++)
	{
	for(level = 0; level < WEAPON_STAGE_NUM; level++)
	{
		if(_weapon_stage[weapon][level][player] != -1)
		{
		if(_weapon_stage[weapon][level][player] != -2)
		{
			if(    (_weapon_stage[weapon][level][player] == 0)
				|| (_weapon_stage[weapon][level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	}
	/* fpv mode */
	for(level = 0; level < FPV_STAGE_NUM; level++)
	{
		if(_fpv_stage[level][player] != -1)
		{
		if(_fpv_stage[level][player] != -2)
		{
			if(    (_fpv_stage[level][player] == 0)
				|| (_fpv_stage[level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	/* variety mode */
	for(level = 0; level < VARIETY_STAGE_NUM; level++)
	{
		if(_variety_stage[level][player] != -1)
		{
		if(_variety_stage[level][player] != -2)
		{
			if(    (_variety_stage[level][player] == 0)
				|| (_variety_stage[level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	/* streaking mode */
	if(player == VRSEL_PLA_X_RAIDEN)
	{
		if(_streaking_stage != -1)
		{
		if(_streaking_stage != -2)
		{
			if(    (_streaking_stage == 0)
				|| (_streaking_stage == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	/* bomb mode */
	for(level = 0; level < BOMB_STAGE_NUM; level++)
	{
		if(_bomb_stage[level][player] != -1)
		{
		if(_bomb_stage[level][player] != -2)
		{
			if(    (_bomb_stage[level][player] == 0)
				|| (_bomb_stage[level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	/* eliminate mode */
	for(level = 0; level < ELIMINATE_STAGE_NUM; level++)
	{
		if(_eliminate_stage[level][player] != -1)
		{
		if(_eliminate_stage[level][player] != -2)
		{
			if(    (_eliminate_stage[level][player] == 0)
				|| (_eliminate_stage[level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	/* holdup mode */
	for(level = 0; level < HOLDUP_STAGE_NUM; level++)
	{
		if(_holdup_stage[level][player] != -1)
		{
		if(_holdup_stage[level][player] != -2)
		{
			if(    (_holdup_stage[level][player] == 0)
				|| (_holdup_stage[level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}
	/* photograph mode */
	for(level = 0; level < PHOTOGRAPH_STAGE_NUM; level++)
	{
		if(_photograph_stage[level][player] != -1)
		{
		if(_photograph_stage[level][player] != -2)
		{
			if(    (_photograph_stage[level][player] == 0)
				|| (_photograph_stage[level][player] == 5))
				not_cleared++;
			else
				cleared++;
		}
		}
	}

	if(cleared + not_cleared == 0)
		return 0;

	return ((cleared * 100) / (cleared + not_cleared));
}

