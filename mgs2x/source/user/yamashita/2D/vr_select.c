/******************************************************************************
 * ステージＩＤの取得
 */
int VRSEL_GetStageID(	/* ステージＩＤ */
	VRSEL_WORK *work)	/* ワーク */
{
	int  player_bit;
	char level;

	/* プレイヤービットの取得 */
	switch(work->player)
	{
	case VRSEL_PLA_RAIDEN  : player_bit = MSN_PLAYER_RAIDEN;   break;
	case VRSEL_PLA_NINJA   : player_bit = MSN_PLAYER_NINJA;    break;
	case VRSEL_PLA_X_RAIDEN: player_bit = MSN_PLAYER_RAIDEN;   break;
	case VRSEL_PLA_SNAKE   : player_bit = MSN_PLAYER_SNAKE;    break;
	case VRSEL_PLA_PLISKIN : player_bit = MSN_PLAYER_PLISKIN;  break;
	case VRSEL_PLA_TUXEDO  : player_bit = MSN_PLAYER_TUXEDO;   break;
	case VRSEL_PLA_PREVIOUS: player_bit = MSN_PLAYER_PREVIOUS; break;
	default:
		return -1;
	}

	/* ステージレベル変換 */
	if(work->level > 9)
		return -1;
	if(work->mode == MSN_MODE_VARIETY)
	{
		switch(work->player)
		{
		case VRSEL_PLA_RAIDEN  : level = work->level; break;
		case VRSEL_PLA_NINJA   :
			if(work->level == 0) level = 4;
			else return -1;
			break;
		case VRSEL_PLA_X_RAIDEN: return -1;
		case VRSEL_PLA_SNAKE   : level = work->level; break;
		case VRSEL_PLA_PLISKIN :
			if     (work->level == 0) level = 3;
			else if(work->level == 1) level = 4;
			else return -1;
			break;
		case VRSEL_PLA_TUXEDO  :
			if     (work->level == 0) level = 3;
			else if(work->level == 1) level = 4;
			else return -1;
			break;
		case VRSEL_PLA_PREVIOUS:
			if     (work->level == 0) level = 3;
			else if(work->level == 1) level = 4;
			else if(work->level == 2) level = 6;
			else return -1;
			break;
		default:
			return -1;
		}
	}
	else
	{
		level = work->level;
	}

	/* ステージＩＤの算出 */
	if(work->missions == MSN_MISSION_VR)
	{
		if(work->mode == MSN_MODE_SNEAKING)
		{
			if(work->weapon == MSN_WEAPON_SNEAKING)           { SY_PRINTF1("vrm sne sne\n"); return VRM_SNK_SNK_START + VRM_SNK_SNK_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_SNK_SNK_PLAYER, player_bit); }
			else if(work->weapon == MSN_WEAPON_ELIMINATE_ALL) { SY_PRINTF1("vrm sne eli\n"); return VRM_SNK_ELM_START + VRM_SNK_ELM_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_SNK_ELM_PLAYER, player_bit); }
			else ASSERT(0);
		}
		else if(work->mode == MSN_MODE_WEAPON)
		{
			if(player_bit & MSN_PLAYER_NINJA)
			{
				if((work->weapon == MSN_WEAPON_HF_BLADE) || (work->weapon == 0)) { SY_PRINTF1("vrm wea hfb\n"); return VRM_WPN_HFB_START + VRM_WPN_HFB_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_HFB_PLAYER, player_bit); }
				else ASSERT(0);
			}
			else
			{
				if((work->weapon == MSN_WEAPON_HANDGUN) || (work->weapon == 0))  { SY_PRINTF1("vrm wea hgn\n"); return VRM_WPN_HGN_START + VRM_WPN_HGN_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_HGN_PLAYER, player_bit); }
				else if(work->weapon == MSN_WEAPON_ASSAULT_RIFLE)                { SY_PRINTF1("vrm wea asr\n"); return VRM_WPN_ASR_START + VRM_WPN_ASR_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_ASR_PLAYER, player_bit); }
				else if(work->weapon == MSN_WEAPON_C4_CLAYMORE)                  { SY_PRINTF1("vrm wea c4c\n"); return VRM_WPN_C4C_START + VRM_WPN_C4C_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_C4C_PLAYER, player_bit); }
				else if(work->weapon == MSN_WEAPON_GRENADE)                      { SY_PRINTF1("vrm wea grn\n"); return VRM_WPN_GRN_START + VRM_WPN_GRN_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_GRN_PLAYER, player_bit); }
				else if(work->weapon == MSN_WEAPON_PSG1)                         { SY_PRINTF1("vrm wea psg\n"); return VRM_WPN_PSG_START + VRM_WPN_PSG_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_PSG_PLAYER, player_bit); }
				else if(work->weapon == MSN_WEAPON_STINGER)                      { SY_PRINTF1("vrm wea stg\n"); return VRM_WPN_STG_START + VRM_WPN_STG_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_STG_PLAYER, player_bit); }
				else if(work->weapon == MSN_WEAPON_NIKITA)                       { SY_PRINTF1("vrm wea nkt\n"); return VRM_WPN_NKT_START + VRM_WPN_NKT_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_NKT_PLAYER, player_bit); }
				else if(work->weapon == MSN_WEAPON_HF_BLADE)                     { SY_PRINTF1("vrm wea hfb\n"); return VRM_WPN_HFB_START + VRM_WPN_HFB_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_WPN_HFB_PLAYER, player_bit); }
				else ASSERT(0);
			}
		}
		else if(work->mode == MSN_MODE_FIRST_PERSON_VIEW) { SY_PRINTF1("vrm fpv\n"); return VRM_FPV_START + VRM_FPV_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_FPV_PLAYER, player_bit); }
		else if(work->mode == MSN_MODE_VARIETY)           { SY_PRINTF1("vrm vrt\n"); return VRM_VRT_START + VRM_VRT_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_VRT_PLAYER, player_bit); }
		else if(work->mode == MSN_MODE_STREAKING)         { SY_PRINTF1("vrm str\n"); return VRM_STR_START + VRM_STR_PLAYER_NUM * level + Msn_GetPlayerNum(VRM_STR_PLAYER, player_bit); }
		else ASSERT(0);
	}
	else if(work->missions == MSN_MISSION_ALTERNATIVE)
	{
		if((work->mode == MSN_MODE_BOMB_DISPOSAL) || (work->mode == 0)) { SY_PRINTF1("alt bmb\n"); return ALT_BMB_START + ALT_BMB_PLAYER_NUM * level + Msn_GetPlayerNum(ALT_BMB_PLAYER, player_bit); }
		else if(work->mode == MSN_MODE_ELIMINATE)                       { SY_PRINTF1("alt elm\n"); return ALT_ELM_START + ALT_ELM_PLAYER_NUM * level + Msn_GetPlayerNum(ALT_ELM_PLAYER, player_bit); }
		else if(work->mode == MSN_MODE_HOLD_UP)                         { SY_PRINTF1("alt hld\n"); return ALT_HLD_START + ALT_HLD_PLAYER_NUM * level + Msn_GetPlayerNum(ALT_HLD_PLAYER, player_bit); }
		else if(work->mode == MSN_MODE_PHOTOGRAPH)                      { SY_PRINTF1("alt pht\n"); return ALT_PHT_START + ALT_PHT_PLAYER_NUM * level + Msn_GetPlayerNum(ALT_PHT_PLAYER, player_bit); }
		else ASSERT(0);
	}
	else ASSERT(0);

	return -1;
}

/******************************************************************************
 * クリアレベルの取得
 */
static int CombineClearLevel(	/* クリアレベル */
	int clear_level_1,	/* クリアレベル１ */
	int clear_level_2,	/* クリアレベル２ */
	int flag)			/* 0: 最低レベル  1:最高レベル */
{
	if(clear_level_1 == 1)
	{
		if(    ((flag == 0) && (clear_level_2 == -2))
			||  (flag == 1))
			clear_level_2 = 1;
	}
	else if(clear_level_1 == 2)
	{
		if(    ((flag == 0) && ((clear_level_2 == -2) || (clear_level_2 == 1)))
			|| ((flag == 1) && ((clear_level_2 == -2) || (clear_level_2 == 5) || (clear_level_2 == 0) || (clear_level_2 == 4) || (clear_level_2 == 3))))
			clear_level_2 = 2;
	}
	else if(clear_level_1 == 3)
	{
		if(    ((flag == 0) && ((clear_level_2 == -2) || (clear_level_2 == 1) || (clear_level_2 == 2)))
			|| ((flag == 1) && ((clear_level_2 == -2) || (clear_level_2 == 5) || (clear_level_2 == 0) || (clear_level_2 == 4))))
			clear_level_2 = 3;
	}
	else if(clear_level_1 == 4)
	{
		if(    ((flag == 0) && ((clear_level_2 == -2) || (clear_level_2 == 1) || (clear_level_2 == 2) || (clear_level_2 == 3)))
			|| ((flag == 1) && ((clear_level_2 == -2) || (clear_level_2 == 5) || (clear_level_2 == 0))))
			clear_level_2 = 4;
	}
	else if(clear_level_1 == 0)
	{
		if(    ((flag == 0) && ((clear_level_2 == -2) || (clear_level_2 == 1) || (clear_level_2 == 2) || (clear_level_2 == 3) || (clear_level_2 == 4)))
			|| ((flag == 1) && ((clear_level_2 == -2) || (clear_level_2 == 5))))
			clear_level_2 = 0;
	}
	else if(clear_level_1 == 5)
	{
		if(     (flag == 0)
			|| ((flag == 1) && (clear_level_2 == -2)))
			clear_level_2 = 5;
	}

	return clear_level_2;
}

int VRSEL_SneakingClearLevel2(	/* クリアレベル */
	VRSEL_WORK *work,	/* ワーク */
	int        weapon,	/* 武器番号 */
	int        player,	/* プレイヤー */
	int        flag)	/* 0: 最低レベル  1:最高レベル */
{
	int level;
	int clear_level;

	clear_level = -2;

	/* sneaking mode */
	for(level = 0; level < SNEAKING_STAGE_NUM; level++)
	{
		if(_sneaking_stage[weapon][level][player] != -1)
		{
		if(_sneaking_stage[weapon][level][player] != -2)
		{
			clear_level = CombineClearLevel(_sneaking_stage[weapon][level][player], clear_level, flag);
		}
		}
	}

	return clear_level;
}
