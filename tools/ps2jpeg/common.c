void tablemk(float _cos[8][8] ,float T_cos[8][8] )
{
    int i,j;

    for( j = 0 ; j < 8 ; j++){
	_cos[0][j] = 1.0f / sqrt(8.0f);
	T_cos[j][0] = _cos[0][j];
    }

    for(i=1 ; i<8 ; i++){
	for(j=0 ; j<8 ;j++){
	    _cos[i][j] = sqrt( 2.0f / 8.0f ) * cos( (2 * j  + 1) * i * PI / 16.0f);
	    T_cos[j][i] = _cos[i][j];
	}
    }
}
